import { useCallback, useEffect, useRef, useState, type ReactNode } from "react";
import { fetchAnalysis, fetchDashboard, fetchHealth, fetchScenarios, fetchSequence, POLL_SECONDS } from "./api";
import type { AnalysisDoc, DashboardDoc, Mode, ScenarioList, SequenceDoc } from "./types";
import { fmtTime } from "./format";
import { Badge, SimulatedBanner, Unavailable } from "./components/common";
import { LiveSimulationPanel } from "./components/simulation";
import { AnalysisSections, DataSourcesStrip } from "./components/analysis";
import {
  AuditSection, EvidenceSection, KpiCards, RiskSection, RiverSection, SafetySection, StateSection,
  TimelineSection, WeatherSection,
} from "./components/sections";

type Load = { doc: DashboardDoc | null; error: string | null; loading: boolean; failedAt: string | null };

export function Header({ online, doc, mode }: { online: boolean | null; doc: DashboardDoc | null; mode: Mode }) {
  return (
    <header className="topbar">
      <div className="brand">
        <h1>Cauvery Flood Disaster Management System</h1>
        <p>Upper Anicut, Tamil Nadu · research prototype · decision support only</p>
      </div>
      <div className="status">
        <Badge tone={online === null ? "neutral" : online ? "ok" : "danger"}>
          API {online === null ? "checking…" : online ? "connected" : "unreachable"}
        </Badge>
        <Badge tone={mode === "real" ? "info" : "sim"}>{MODE_LABEL[mode]}</Badge>
        <span className="updated">
          Last update: {doc ? fmtTime(doc.generated_at) : "—"}
          {doc && typeof doc.cache_age_seconds === "number" && doc.cache_age_seconds > 0 && ` (cached ${Math.round(doc.cache_age_seconds)} s)`}
          <br />Timezone: Asia/Kolkata (IST, UTC+05:30)
        </span>
      </div>
    </header>
  );
}

/** ``sources`` goes under the summary cards and ``afterRiver`` directly after the River
 *  monitoring section (real mode: the separately fetched historical analysis). */
export function Dashboard({ doc, sources, afterRiver }: { doc: DashboardDoc; sources?: ReactNode; afterRiver?: ReactNode }) {
  return (
    <>
      {doc.mode === "simulated_live" ? (
        <>
          <SimulatedBanner label="SIMULATED LIVE" text={`Real-time simulation "${doc.scenario}" (${doc.scenario_description ?? ""}), started in ${doc.start_state ?? "NORMAL"}; the state then changes only by automatic evaluation. Readings are generated by this system every ${doc.simulation?.interval_minutes ?? 5} minutes with current timestamps. They are NOT Central Water Commission observations, use TEST thresholds, and can never authorize a real-world action.`} />
          <LiveSimulationPanel doc={doc} />
        </>
      ) : doc.is_simulated && (
        <SimulatedBanner text={`Scenario "${doc.scenario}" (${doc.scenario_description ?? ""}), evaluated automatically from ${doc.start_state ?? "NORMAL"}. Fabricated river and weather data, TEST thresholds; never real conditions, never saved to the real state record.`} />
      )}
      <KpiCards doc={doc} />
      {sources}
      <div className="layout">
        <WeatherSection doc={doc} />
        <RiverSection doc={doc} />
        {afterRiver}
        <RiskSection doc={doc} />
        <StateSection doc={doc} />
        <SafetySection doc={doc} />
        <EvidenceSection doc={doc} />
        <AuditSection doc={doc} />
      </div>
    </>
  );
}

const LIVE_SCENARIOS = ["stable", "slowly-rising", "rapidly-rising", "falling", "flood-wave"];
const MODE_LABEL: Record<Mode, string> = {
  real: "REAL DATA", simulated: "SIMULATED DATA", simulated_live: "SIMULATED LIVE",
};

/** Optional starting view from the URL (?mode=simulated|simulated_live&scenario=...), for
 *  shareable demo links. Real mode stays the default; the backend validates names. There is
 *  no state parameter: the disaster state is evaluated automatically by the backend. */
function initialView() {
  const q = typeof window === "undefined" ? new URLSearchParams() : new URLSearchParams(window.location.search);
  const scenario = q.get("scenario") ?? "";
  const mode = (["simulated", "simulated_live"].includes(q.get("mode") ?? "") ? q.get("mode") : "real") as Mode;
  return {
    mode,
    scenario: mode === "simulated" && /^[a-z0-9-]{1,64}$/.test(scenario) ? scenario : "rising-river-increasing-rain",
    liveScenario: mode === "simulated_live" && LIVE_SCENARIOS.includes(scenario) ? scenario : "stable",
  };
}

export default function App() {
  const [initial] = useState(initialView);
  const [mode, setMode] = useState<Mode>(initial.mode);  // real unless asked; never switched automatically
  const [scenario, setScenario] = useState(initial.scenario);
  const [liveScenario, setLiveScenario] = useState(initial.liveScenario);
  const [scenarios, setScenarios] = useState<ScenarioList | null>(null);
  const [online, setOnline] = useState<boolean | null>(null);
  const [load, setLoad] = useState<Load>({ doc: null, error: null, loading: true, failedAt: null });
  const [seq, setSeq] = useState<{ doc: SequenceDoc | null; error: string | null }>({ doc: null, error: null });
  // Historical analysis: a separate document, shown in real mode only and never mixed into it.
  const [analysis, setAnalysis] = useState<{ doc: AnalysisDoc | null; error: string | null }>({ doc: null, error: null });
  const inFlight = useRef<AbortController | null>(null);

  const refresh = useCallback(async () => {
    if (inFlight.current) return;  // no duplicate requests
    const controller = new AbortController();
    inFlight.current = controller;
    setLoad((l) => ({ ...l, loading: true }));
    try {
      const [health, result] = await Promise.all([
        fetchHealth(controller.signal).catch(() => false),
        fetchDashboard(mode, mode === "simulated_live" ? liveScenario : scenario, controller.signal),
      ]);
      setOnline(health);
      setLoad((l) => result.ok
        ? { doc: result.value, error: null, loading: false, failedAt: null }
        // Keep the last good document but say clearly that it is old.
        : { doc: l.doc?.mode === mode ? l.doc : null, error: result.error, loading: false, failedAt: new Date().toISOString() });
    } catch (err) {
      if ((err as Error).name !== "AbortError") setLoad((l) => ({ ...l, loading: false, error: String(err) }));
    } finally {
      if (inFlight.current === controller) inFlight.current = null;
    }
  }, [mode, scenario, liveScenario]);

  // Changing mode or scenario: drop the old document so modes never mix on screen.
  useEffect(() => {
    inFlight.current?.abort();
    inFlight.current = null;
    setLoad({ doc: null, error: null, loading: true, failedAt: null });
    void refresh();
    if (mode === "simulated") return;  // scenario documents are fixed; no polling
    const id = window.setInterval(() => void refresh(), POLL_SECONDS * 1000);
    return () => window.clearInterval(id);
  }, [mode, refresh]);

  useEffect(() => {
    if (mode === "real") return;
    const controller = new AbortController();
    if (!scenarios) void fetchScenarios(controller.signal).then((r) => r.ok && setScenarios(r.value)).catch(() => undefined);
    if (mode === "simulated" && !seq.doc) void fetchSequence("flood-cycle", controller.signal)
      .then((r) => setSeq(r.ok ? { doc: r.value, error: null } : { doc: null, error: r.error }))
      .catch(() => undefined);
    return () => controller.abort();
  }, [mode, scenarios, seq.doc]);

  useEffect(() => {
    if (mode !== "real" || analysis.doc) return;
    const controller = new AbortController();
    void fetchAnalysis(controller.signal)
      .then((r) => setAnalysis(r.ok ? { doc: r.value, error: null } : { doc: null, error: r.error }))
      .catch(() => undefined);
    return () => controller.abort();
  }, [mode, analysis.doc]);

  const doc = load.doc && load.doc.mode === mode ? load.doc : null;
  return (
    <div className={`app ${mode === "real" ? "" : "is-sim"}`}>
      <Header online={online} doc={doc} mode={mode} />
      <nav className="modebar" aria-label="Data mode">
        <div className="segmented" role="radiogroup" aria-label="Mode">
          <button role="radio" aria-checked={mode === "real"} className={mode === "real" ? "on" : ""} onClick={() => setMode("real")}>Real CWC Data</button>
          <button role="radio" aria-checked={mode === "simulated_live"} className={mode === "simulated_live" ? "on sim" : ""} onClick={() => setMode("simulated_live")}>Real-Time River Simulation</button>
          <button role="radio" aria-checked={mode === "simulated"} className={mode === "simulated" ? "on sim" : ""} onClick={() => setMode("simulated")}>Simulated demo</button>
        </div>
        {mode === "simulated_live" && (
          <label>River scenario
            <select value={liveScenario} onChange={(e) => setLiveScenario(e.target.value)}>
              {(scenarios?.live_simulation?.scenarios?.map((s) => s.name) ?? LIVE_SCENARIOS).map((s) => <option key={s} value={s}>{s}</option>)}
            </select>
          </label>
        )}
        {mode === "simulated" && <label>Scenario
          <select value={scenario} onChange={(e) => setScenario(e.target.value)}>
            {(scenarios?.scenarios ?? [{ name: scenario, description: "" }]).map((s) => <option key={s.name} value={s.name}>{s.name}</option>)}
          </select>
        </label>}
        <span className="badge badge-info" title="The disaster state cannot be selected: the backend evaluates it from the river, weather and traffic evidence.">AUTOMATIC STATE EVALUATION</span>
        <button className="ghost" onClick={() => void refresh()} disabled={load.loading} title="Reload the read-only dashboard data">
          {load.loading ? "Loading…" : "Reload data"}
        </button>
        <span className="small muted">{mode === "real" ? `Refreshes every ${POLL_SECONDS} s (backend caches 5 min)`
          : mode === "simulated_live" ? `Checks every ${POLL_SECONDS} s; a new SIMULATED reading every ${scenarios?.live_simulation?.interval_minutes ?? 5} min`
          : "Simulated results are fixed; no polling"}</span>
      </nav>

      <main>
        {load.error && (
          <div className="alert" role="alert">
            <strong>{doc ? "Latest refresh failed — showing the previous data." : "Data unavailable."}</strong> {load.error}
            {load.failedAt && <> ({fmtTime(load.failedAt)})</>}
          </div>
        )}
        {!doc && load.loading && <Unavailable>Loading {MODE_LABEL[mode].toLowerCase()}…</Unavailable>}
        {!doc && !load.loading && !load.error && <Unavailable>No data.</Unavailable>}
        {doc && (mode === "real"
          ? <Dashboard doc={doc}
              sources={<DataSourcesStrip doc={doc} analysis={analysis.doc} analysisError={analysis.error} />}
              afterRiver={analysis.doc ? <AnalysisSections doc={analysis.doc} />
                : <Unavailable>{analysis.error ? `Historical CWC analysis unavailable: ${analysis.error}` : "Loading historical CWC analysis (reading the local export)…"}</Unavailable>} />
          : <Dashboard doc={doc} />)}
        {mode === "real" && !doc && analysis.doc && (
          // The live-feed document failed or is loading: the historical analysis stays reachable.
          <div className="layout"><AnalysisSections doc={analysis.doc} /></div>
        )}
        {mode === "simulated" && <TimelineSection seq={seq.doc} error={seq.error} />}

      </main>
      <footer className="foot">
        Research prototype. Prototype thresholds are not official flood-warning levels. No real-world
        action can be taken from this page; every real-world capability needs human approval in the backend.
      </footer>
    </div>
  );
}
