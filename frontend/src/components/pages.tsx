// The eight dashboard pages. Each renders the normalized View (src/model.ts); every
// number and every sentence comes from the backend.
import { useState, type ReactNode } from "react";
import type { ThresholdCheck, View } from "../model";
import { AGENT_TONE, RISK_TONE, STATE_TONE, TRUST_TONE } from "../model";
import type { AnalysisDoc } from "../types";
import { fmtAge, fmtNum, fmtTime, isNum } from "../format";
import { ForecastAnalyticsPage } from "./analytics";
import { RiverRainPanel, StateStrip, TimeChart, type RangeHours } from "./charts";
import {
  AgentCardView, CapabilityCardView, CapabilityMini, Progress, RiskBands, RiskGauge, StateSummary,
  StateTimeline, TransitionList, TrustDeductions, TrustFactors, TrustGauge, WhyRisk,
} from "./panels";
import { Card, Disclosure, Empty, Icon, Id, KV, PageHeader, Pill, Stat } from "./ui";

export const PAGES = [
  { id: "overview", label: "Overview", icon: "overview" },
  { id: "monitoring", label: "Live Monitoring", icon: "monitor" },
  { id: "risk", label: "Risk Assessment", icon: "risk" },
  { id: "evidence", label: "Evidence Intelligence", icon: "evidence" },
  { id: "state", label: "Disaster State", icon: "state" },
  { id: "capabilities", label: "Capability Control", icon: "capability" },
  { id: "analytics", label: "Forecast & Analytics", icon: "analytics" },
  { id: "history", label: "Activity History", icon: "history" },
] as const;
export type PageId = (typeof PAGES)[number]["id"];

function NoInsights({ view }: { view: View }) {
  return <Empty>Assessment details are unavailable for this response{view.insightsError ? `: ${view.insightsError}` : "."}</Empty>;
}

function rainLabel(view: View) {
  if (view.source === "simulation") return "Rain per hour (SIMULATED LIVE scenario)";
  if (view.source === "scenario") return "Rain per hour (simulated test case)";
  return "Rain per hour (Open-Meteo model)";
}

/** River level and rainfall on one time axis, with a 1/6/12/24 h range selector. Every point
 *  is a backend reading; the range only selects which ones are shown. */
export function RiverRainCard({ view, title = "River level and rainfall", initialRange = 24 }: {
  view: View; title?: string; initialRange?: RangeHours;
}) {
  const [range, setRange] = useState<RangeHours>(initialRange);
  const kind = view.river.official ? "official" : "research/test values, not official";
  return (
    <Card title={title} icon="river"
      subtitle={`metres · mm · ${view.label} · thresholds: ${kind}`}>
      <RiverRainPanel river={view.river} rain={view.rain} rainLabel={rainLabel(view)} range={range} onRange={setRange} />
    </Card>
  );
}

function sourceNote(view: View) {
  return view.simulated
    ? `${view.label}: generated by this system. Not Central Water Commission observations.`
    : "Real data from the configured live sources.";
}

// ---- 1. Overview -------------------------------------------------------------------------

export function OverviewPage({ view }: { view: View }) {
  const ins = view.insights;
  if (!ins) return <NoInsights view={view} />;
  const { risk_score: risk, trust, state, agents } = ins;
  return (
    <div className="page">
      <section className="headline" aria-label="What is happening">
        <Icon name="info" size={18} />
        <p>{ins.headline}</p>
      </section>
      <div className="grid grid-4">
        <Card title="Flood risk" icon="risk" className="hero">
          <div className="hero-body">
            <RiskGauge risk={risk} size={132} />
            <p className="hero-text">{risk.summary}</p>
          </div>
        </Card>
        <Card title="Evidence trust" icon="evidence" className="hero">
          <div className="hero-body">
            <TrustGauge trust={trust} size={132} />
            <p className="hero-text">How reliable the evidence is — not how dangerous the flood is.
              {trust.is_simulated && <> <strong>Simulated</strong>, not verified real-world evidence.</>}</p>
          </div>
        </Card>
        <Card title="Disaster state" icon="state" className="hero">
          <StateSummary state={state} compact />
          <StateTimeline state={state} />
        </Card>
        <Card title="Agents supplying evidence" icon="monitor" className="hero">
          <ul className="agent-mini">
            {(["weather", "river", "traffic"] as const).map((k) => (
              <li key={k}>
                <span className="agent-mini-name"><Icon name={k === "weather" ? "rain" : k} size={15} /> {agents[k].agent}</span>
                <Pill tone={AGENT_TONE[agents[k].status]}>{agents[k].status}</Pill>
                <span className="agent-mini-tells">{agents[k].tells}</span>
              </li>
            ))}
          </ul>
        </Card>
      </div>
      <div className="grid grid-2">
        <Card title="Why this risk level?" icon="risk"><WhyRisk ins={ins} compact /></Card>
        <Card title="Capabilities in this state" icon="capability"
          subtitle={`Decided by the backend permission policy for ${state.current}. Nothing here executes an action.`}>
          <CapabilityMini cards={ins.capabilities} />
        </Card>
      </div>
      <RiverRainCard view={view} />
    </div>
  );
}

// ---- 2. Live Monitoring ------------------------------------------------------------------

export function MonitoringPage({ view }: { view: View }) {
  const ins = view.insights;
  const river = ins?.agents.river.metrics ?? {};
  const weather = ins?.agents.weather.metrics ?? {};
  const n = (o: Record<string, unknown>, k: string) => (isNum(o[k]) ? (o[k] as number) : null);
  const rate = n(river, "rate_m_per_hour");
  return (
    <div className="page">
      <PageHeader title="Live Monitoring" lead={`Latest readings and their history. ${sourceNote(view)}`} />
      <div className="stats">
        <Stat label="River level" value={fmtNum(n(river, "level_m"), "m", 3)} note={view.latest ? <>Reading <Id value={view.latest.observation_id} /></> : fmtTime(river.observed_at as string)} />
        <Stat label="Rate of change" value={rate === null ? "—" : `${rate >= 0 ? "+" : ""}${fmtNum(rate, "m/h", 3)}`} note={String(river.trend ?? "").toLowerCase() || "trend unknown"} />
        <Stat label="Rain, past 24 h" value={fmtNum(n(weather, "rain_24h_mm"), "mm", 1)} note={`last hour ${fmtNum(view.latest?.rain_mm_last_hour ?? null, "mm", 1)}`} />
        <Stat label="Forecast rain" value={fmtNum(n(weather, "forecast_mm"), "mm", 1)} note={`next ${String(weather.forecast_hours ?? 24)} h`} />
        <Stat label={view.sim ? "Simulation time" : "Evaluated"} value={<span className="stat-time">{fmtTime(view.evaluatedAt)}</span>}
          note={view.sim ? `step ${view.sim.tick} · ${view.sim.simulated_minutes_per_tick} simulated min per tick` : `evidence ${fmtAge(n(river, "age_hours"))}`} />
      </div>
      <RiverRainCard view={view} title="River level and rainfall over time" initialRange={12} />
      <div className="grid grid-2">
        <Card title="River-level rate of change" icon="monitor" subtitle="m/h, as computed by the River Agent's trend (3 h window)">
          {view.rate.length ? <TimeChart data={view.rate} unit="m/h" digits={3} name="Rate of change"
            refs={[{ y: 0, label: "steady", color: "#8a99ad" }, { y: 0.1, label: "rise 0.10 (prototype)", color: "#b7791f" }, { y: 0.3, label: "rapid 0.30 (prototype)", color: "#c0392b" }]} />
            : <Empty>{view.historyNote ?? "No rate history yet."}</Empty>}
        </Card>
        <Card title="Flood risk score history" icon="risk" subtitle="0–100; bands at 25 / 50 / 75 (prototype presentation bands)">
          {view.risk.length ? <>
            <TimeChart data={view.risk.flatMap((r) => (r.v === null ? [] : [{ t: r.t, v: r.v }]))} unit="" digits={0} name="Risk score" domain={[0, 100]}
              refs={[{ y: 25, label: "Moderate", color: "#b7791f" }, { y: 50, label: "High", color: "#c96a1b" }, { y: 75, label: "Critical", color: "#c0392b" }]} />
            {view.risk.some((r) => r.v === null) && <p className="small muted">Gaps are INDETERMINATE evaluations: no score is drawn for them.</p>}
          </> : <Empty>{view.historyNote ?? "No history yet."}</Empty>}
        </Card>
        <Card title="Evidence trust history" icon="evidence" subtitle="0–100; HIGH from 80, MODERATE from 60, LOW from 30">
          {view.trust.length ? <TimeChart data={view.trust} unit="" digits={0} name="Trust score" domain={[0, 100]}
            refs={[{ y: 80, label: "High trust", color: "#2f7d4f" }, { y: 60, label: "Moderate", color: "#b7791f" }, { y: 30, label: "Low", color: "#c0392b" }]} />
            : <Empty>{view.historyNote ?? "No history yet."}</Empty>}
        </Card>
        <Card title="Disaster-state timeline" icon="state" subtitle="Accepted state after each evaluation">
          {view.states.length ? <StateStrip states={view.states} /> : <Empty>{view.historyNote ?? "No state history yet."}</Empty>}
          {view.transitions.length > 0 && <p className="small muted">{view.transitions.length} automatic transition(s); see Disaster State.</p>}
        </Card>
      </div>
    </div>
  );
}

// ---- 3. Risk Assessment ------------------------------------------------------------------

export function RiskPage({ view }: { view: View }) {
  const ins = view.insights;
  if (!ins) return <NoInsights view={view} />;
  const risk = ins.risk_score;
  const ex = ins.risk_explanation;
  return (
    <div className="page">
      <PageHeader title="Risk Assessment" lead="Flood risk from the deterministic Risk Assessment Engine. The score positions the engine's category inside its presentation band; hazard thresholds are configured separately." />
      <div className="grid grid-risk">
        <Card title="Flood risk score" icon="risk">
          <div className="risk-hero">
            <RiskGauge risk={risk} size={168} />
            <div>
              <p className="lead-text">{risk.summary}</p>
              <RiskBands risk={risk} />
              <p className="small muted">Bands are prototype presentation bands, not official CWC flood-warning levels.
                {risk.confidence && ` Engine confidence: ${risk.confidence.toLowerCase()}.`}</p>
            </div>
          </div>
        </Card>
        <Card title="Why this risk level?" icon="info"><WhyRisk ins={ins} /></Card>
      </div>
      <Card title="Contributing factors" icon="monitor" subtitle="Each indicator is indexed 0–100 in the band of the engine's own level for it. The score is the dominant indicator plus corroboration — never an average.">
        {risk.factors.length ? (
          <ul className="factors">
            {risk.factors.map((f) => (
              <li key={f.key} className={`factor dir-${f.direction}`}>
                <div className="factor-row">
                  <span className="factor-name">{f.label}{f.context_only && <span className="muted"> · context only</span>}</span>
                  <span className="factor-value">{f.value_text}</span>
                  <Pill tone={f.level ? RISK_TONE[f.level] ?? "neutral" : "neutral"} icon={false}>{f.level ?? "context"}</Pill>
                </div>
                <div className="factor-bar"><div style={{ width: `${f.index ?? 0}%` }} className={`fb-${f.level ? RISK_TONE[f.level] : "neutral"}`} /></div>
                <span className="factor-detail">{f.detail}{f.rule_id ? ` · rule ${f.rule_id.split("_")[0]}` : ""}</span>
              </li>
            ))}
          </ul>
        ) : <Empty>No indicators could be evaluated.</Empty>}
        {ex.raising.length + ex.lowering.length > 0 && (
          <div className="contrib">
            <div><h4><Icon name="up" size={14} /> Raising the risk</h4><p>{ex.raising.join(", ") || "none"}</p></div>
            <div><h4><Icon name="down" size={14} /> Keeping it lower</h4><p>{ex.lowering.join(", ") || "none"}</p></div>
          </div>
        )}
      </Card>
      <Disclosure summary="Engine rules fired, decision trace and uncertainties">
        <h4>Rules fired</h4>
        <ul className="plain">{ex.rules.map((r, i) => <li key={i}><code>{r.rule_id}</code> {r.level && <strong>{r.level}</strong>} — {r.description}</li>)}</ul>
        <h4>Decision trace</h4>
        <ol className="plain">{ex.trace.map((t, i) => <li key={i}>{t}</li>)}</ol>
        <h4>Uncertainties</h4>
        <ul className="plain">{ex.uncertainties.map((u, i) => <li key={i}>{u}</li>)}</ul>
        <p className="small muted">{risk.method}</p>
      </Disclosure>
    </div>
  );
}

// ---- 4. Evidence Intelligence ------------------------------------------------------------

export function EvidencePage({ view }: { view: View }) {
  const ins = view.insights;
  if (!ins) return <NoInsights view={view} />;
  const s = ins.evidence_summary;
  const trust = ins.trust;
  const counts: [string, number, string][] = [
    ["Accepted", s.accepted, "ok"], ["Rejected", s.rejected, "warn"], ["Stale", s.stale, "caution"],
    ["Missing", s.missing, "warn"], ["Conflicting", s.conflicting, "danger"],
  ];
  return (
    <div className="page">
      <PageHeader title="Evidence Intelligence" lead="What each agent supplied, whether the system accepted it, and how reliable the evidence is overall." />
      <div className="counts" role="list" aria-label="Evidence summary">
        {counts.map(([label, value, tone]) => (
          <div key={label} role="listitem" className={`count ${value > 0 ? `count-${tone}` : ""}`}><strong>{value}</strong><span>{label}</span></div>
        ))}
        <div role="listitem" className="count"><strong>{s.reverification.outcome ? s.reverification.outcome.replace(/_/g, " ").toLowerCase() : "—"}</strong><span>Reverification</span></div>
      </div>
      <div className="grid grid-3">
        <AgentCardView card={ins.agents.weather} />
        <AgentCardView card={ins.agents.river} />
        <AgentCardView card={ins.agents.traffic} />
      </div>
      <div className="grid grid-trust">
        <Card title="Evidence trust score" icon="evidence">
          <div className="trust-hero">
            <TrustGauge trust={trust} size={150} />
            <div className="trust-mini">
              <Stat label="Source reliability" value={trust.source_reliability} tone={TRUST_TONE[trust.source_reliability >= 80 ? "HIGH" : trust.source_reliability >= 60 ? "MODERATE" : "LOW"]} />
              <Stat label="Freshness" value={trust.freshness} />
              <Stat label="Completeness" value={trust.completeness} />
              <Stat label="Consistency" value={trust.consistency} />
            </div>
          </div>
          {trust.simulated_note && <p className="sim-note"><Icon name="info" size={14} /> {trust.simulated_note}</p>}
          {trust.caps.map((c, i) => <p key={i} className="cap-note"><Icon name="alert" size={14} /> Capped at {c.cap}: {c.reason}</p>)}
        </Card>
        <Card title="Trust factors" icon="monitor"><TrustFactors trust={trust} /></Card>
        <Card title="Reasons for deductions" icon="info"><TrustDeductions trust={trust} />
          <p className="small muted">{trust.method}</p></Card>
      </div>
      <Disclosure summary={`Technical evidence records (${view.records.length}) and claims (${view.claims.length})`}>
        <table className="tbl">
          <thead><tr><th>Evidence ID</th><th>Kind</th><th>Class</th><th>Observed</th><th>Validation</th></tr></thead>
          <tbody>{view.records.map((r, i) => (
            <tr key={i}><td><Id value={r.evidence_id} /></td><td>{r.kind}</td><td>{r.evidence_class}</td><td>{fmtTime(r.observed_at)}</td>
              <td>{r.validation}{r.findings?.length ? ` (${r.findings.join(", ").toLowerCase().replace(/_/g, " ")})` : ""}</td></tr>
          ))}</tbody>
        </table>
        <ul className="plain claims">{view.claims.map((c, i) => <li key={i}><Pill tone={c.status === "SUPPORTED" ? "ok" : c.status === "SIMULATED_ONLY" ? "info" : "caution"} icon={false}>{c.status}</Pill> {c.statement}</li>)}</ul>
        {s.deny_reasons.length > 0 && <p className="small muted">Real-world use denied by the Evidence Layer: {s.deny_reasons.join("; ")}.</p>}
      </Disclosure>
    </div>
  );
}

// ---- 5. Disaster State -------------------------------------------------------------------

export function StatePage({ view }: { view: View }) {
  const ins = view.insights;
  if (!ins) return <NoInsights view={view} />;
  const st = ins.state;
  const last = st.last_transition;
  return (
    <div className="page">
      <PageHeader title="Disaster State" lead="Selected automatically by the Disaster State Manager from the evidence: deterministic rules, minimum persistence, hysteresis and legal transitions only. It cannot be set from this page." />
      <Card title="State timeline" icon="state">
        <StateTimeline state={st} />
      </Card>
      <div className="grid grid-2">
        <Card title="Current state and why" icon="info">
          <StateSummary state={st} />
          <ul className="plain small">{st.reasons.map((r, i) => <li key={i}>{r}</li>)}</ul>
          <Progress state={st} />
        </Card>
        <Card title="Evaluation" icon="clock">
          <KV items={[
            ["Evaluated at", fmtTime(st.evaluated_at)],
            ["Observation", fmtTime(st.observed_at)],
            ["Outcome", (st.outcome ?? "—").replace(/_/g, " ").toLowerCase()],
            ["Previous state", st.previous ?? "—"],
            ["Proposed next", st.proposed_next ?? "none"],
            ["Last transition", last ? `${last.from} → ${last.to} (${last.kind ?? ""}) at ${fmtTime(last.at)}` : "none yet"],
            ["River vs thresholds", thresholdText(st.threshold_check)],
            ["Applies to", (st.applies_to ?? "—").replace(/_/g, " ").toLowerCase()],
          ]} />
          <Disclosure summary="Evidence used for this evaluation">
            <KV items={[["River evidence", <Id value={st.evidence_used.river_evidence_id} />],
              ["Risk assessment", <Id value={st.evidence_used.risk_assessment_id} />],
              ["Risk level", st.evidence_used.risk_level ?? "—"],
              ["Supporting observations", st.evidence_used.supporting_evidence_ids.length ? st.evidence_used.supporting_evidence_ids.map((x) => <Id key={x} value={x} />) : "—"]]} />
          </Disclosure>
        </Card>
      </div>
      <Card title={`Rules out of ${st.current}`} icon="arrow" subtitle="Research/test persistence values from config/disaster_state.json — not official criteria.">
        <ul className="plain">{st.next_rules.map((r, i) => <li key={i}><Pill tone={STATE_TONE[r.to] ?? "neutral"} icon={false}>{r.to}</Pill> {r.kind}: {r.text}</li>)}</ul>
      </Card>
      <Card title="Transition history" icon="history" subtitle={view.simulated ? "Simulation history only — kept separate from the real operational record." : "Real operational record."}>
        <TransitionList transitions={view.transitions} />
      </Card>
    </div>
  );
}

function thresholdText(tc?: ThresholdCheck | null) {
  if (!tc || !tc.configured) return "no configured thresholds for this station";
  return `${fmtNum(tc.level_m, "m", 2)} · warning ${fmtNum(tc.warning_level_m, "m", 2)} · danger ${fmtNum(tc.danger_level_m, "m", 2)}`
    + (isNum(tc.recovery_level_m) ? ` · recovery ${fmtNum(tc.recovery_level_m, "m", 2)}` : "") + ` (${tc.label})`;
}

// ---- 6. Capability Control ---------------------------------------------------------------

export function CapabilitiesPage({ view }: { view: View }) {
  const ins = view.insights;
  if (!ins) return <NoInsights view={view} />;
  return (
    <div className="page">
      <PageHeader title="Capability Control" lead={`Permissions for the ${ins.state.current} state, recalculated by the backend after every accepted transition. The system never executes evacuations, dispatches or public alerts: real-world capabilities can at most be proposed to a human.`}>
        <div className="legend-pills"><Pill tone="ok">ALLOWED</Pill><Pill tone="caution">RESTRICTED</Pill><Pill tone="danger">DENIED</Pill></div>
      </PageHeader>
      <div className="grid grid-caps">{ins.capabilities.map((c) => <CapabilityCardView key={c.capability} card={c} />)}</div>
      <p className="small muted">ALLOWED: permitted in this state and the evidence gate passed. RESTRICTED: permitted in this state but blocked by the evidence gate (e.g. simulated, stale or conflicting evidence). DENIED: not on this state's allowlist.</p>
    </div>
  );
}

// ---- 7. Forecast & Analytics ----------------------------------------------------------------

export function AnalyticsPage({ analysis, error }: { analysis: AnalysisDoc | null; error: string | null }) {
  return <ForecastAnalyticsPage analysis={analysis} error={error} />;
}

// ---- 8. Activity History ----------------------------------------------------------------

export function HistoryPage({ view }: { view: View }) {
  return (
    <div className="page">
      <PageHeader title="Activity History" lead={view.simulated ? "Simulation activity, kept separate from the real operational history." : "Recent audited events of the real workflow."} />
      <div className="grid grid-2">
        <Card title="Activity" icon="history">
          {view.activity.length ? (
            <ol className="feed">
              {view.activity.slice(0, 60).map((a, i) => (
                <li key={i} className={`feed-${a.kind}`}>
                  <time>{fmtTime(a.sim_time ?? a.wall_time)}</time>
                  <span className="feed-kind">{a.kind}</span>
                  <span className="feed-text">{a.text}</span>
                </li>
              ))}
            </ol>
          ) : <Empty>No activity recorded.</Empty>}
        </Card>
        <div className="stack">
          <Card title="Automatic transitions" icon="state"><TransitionList transitions={view.transitions} /></Card>
          <Card title="Audit trail" icon="lock" subtitle={view.simulated ? "In-memory simulation audit (never the real audit log)" : "Workflow audit events"}>
            {view.audit.length ? (
              <ul className="audit-list">{view.audit.slice(0, 25).map((e, i) => <li key={i}><time>{fmtTime(e.at)}</time><code>{e.event}</code></li>)}</ul>
            ) : <Empty>No audit events in this response.</Empty>}
          </Card>
        </div>
      </div>
    </div>
  );
}

export function renderPage(page: PageId, view: View, analysis: AnalysisDoc | null, analysisError: string | null): ReactNode {
  switch (page) {
    case "monitoring": return <MonitoringPage view={view} />;
    case "risk": return <RiskPage view={view} />;
    case "evidence": return <EvidencePage view={view} />;
    case "state": return <StatePage view={view} />;
    case "capabilities": return <CapabilitiesPage view={view} />;
    case "analytics": return <AnalyticsPage analysis={analysis} error={analysisError} />;
    case "history": return <HistoryPage view={view} />;
    default: return <OverviewPage view={view} />;
  }
}
