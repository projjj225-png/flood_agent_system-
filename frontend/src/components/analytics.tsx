/** Readings more than this apart are drawn with a break, never joined (gaps stay gaps). */
const GAP_FACTOR = 3;

export function historicalChartData(series: SeriesDoc) {
  const pts = series.points.flatMap((p) => { const t = epoch(p.time); return t !== null && isNum(p.level_m) ? [{ t, v: p.level_m as number | null }] : []; });
  if (pts.length < 3) return pts;
  const steps = pts.slice(1).map((p, i) => p.t - pts[i].t).sort((a, b) => a - b);
  const typical = steps[Math.floor(steps.length / 2)] || 1;
  const out: { t: number; v: number | null }[] = [pts[0]];
  for (let i = 1; i < pts.length; i++) {
    if (pts[i].t - pts[i - 1].t > Math.max(GAP_FACTOR * typical, 3 * 3600_000)) out.push({ t: pts[i - 1].t + 1, v: null });
    out.push(pts[i]);
  }
  return out;
}

/** Presentation thresholds for the QC-acceptance indicator (not hydrological criteria). */
export function qualityTone(pct: number | null | undefined) {
  if (!isNum(pct)) return { tone: "unknown" as const, label: "UNKNOWN" };
  if (pct >= 90) return { tone: "ok" as const, label: "GOOD" };
  if (pct >= 60) return { tone: "caution" as const, label: "FAIR" };
  return { tone: "danger" as const, label: "POOR" };
}

export function HistoricalSection({ doc, series, error, loading, station, range, onStation, onRange }: {
  doc: AnalysisDoc; series: SeriesDoc | null; error: string | null; loading: boolean;
  station: string; range: SeriesRange; onStation: (s: string) => void; onRange: (r: SeriesRange) => void;
}) {
  const stations = series?.stations ?? Object.keys(doc.analysis?.stations ?? {});
  const meta = doc.analysis?.stations?.[station];
  const q = series?.quality;
  const quality = qualityTone(q?.accepted_pct);
  const data = series ? historicalChartData(series) : [];
  const shown = series && series.station_id === station && series.range === range;
  let body: ReactNode;
  if (error) body = <Empty>Historical readings unavailable: {error}</Empty>;
  else if (!shown) body = <Empty>{loading ? "Loading readings…" : "No readings loaded."}</Empty>;
  else if (!series.stats) body = <Empty>{series.reason ?? "No accepted readings in this range."}</Empty>;
  else body = (
    <>
      <div className="fa-metrics">
        <Stat label="Latest" value={fmtNum(series.latest?.level_m, "m", 2)} note={fmtShort(series.latest?.observed_at)} />
        <Stat label="Minimum" value={fmtNum(series.stats.min_m, "m", 2)} />
        <Stat label="Maximum" value={fmtNum(series.stats.max_m, "m", 2)} />
        <Stat label="Average" value={fmtNum(series.stats.mean_m, "m", 2)} note={`${series.stats.readings} readings`} />
        <Stat label="Data quality" value={<Pill tone={quality.tone}>{quality.label}</Pill>}
          note={isNum(q?.accepted_pct) ? `${q!.accepted_pct}% passed QC` : undefined} />
      </div>
      {data.length >= 2 ? (
        <figure className="chart" aria-label={`${stationName(station)} river level, ${range}`}>
          <ResponsiveContainer width="100%" height={260}>
            <LineChart data={data} margin={{ top: 8, right: 16, bottom: 0, left: 0 }}>
              <CartesianGrid stroke={GRID} vertical={false} />
              <XAxis dataKey="t" type="number" scale="time" domain={["dataMin", "dataMax"]} tick={AXIS} stroke={GRID} minTickGap={56}
                tickFormatter={(t: number) => range === "all" ? new Date(t).toISOString().slice(0, 7) : fmtShort(new Date(t).toISOString())} />
              <YAxis domain={["auto", "auto"]} tick={AXIS} width={52} stroke={GRID} tickFormatter={(v: number) => v.toFixed(1)} />
              <Tooltip labelFormatter={(t) => (typeof t === "number" ? `${fmtShort(new Date(t).toISOString())} IST` : "")}
                formatter={(v: number) => [fmtNum(v, "m", 3), "River level"]} />
              <Line type="linear" dataKey="v" stroke={INK} strokeWidth={range === "all" ? 1 : 2} dot={data.length < 30}
                connectNulls={false} isAnimationActive={false} />
            </LineChart>
          </ResponsiveContainer>
          {series.thinned && <figcaption className="small muted">Long range: each time slot shows its lowest and highest actual reading.</figcaption>}
        </figure>
      ) : <Empty>Too few readings in this range to draw a line.</Empty>}
      <Disclosure summary="Data details">
        <KV items={[
          ["Window", `${fmtTime(series.window_start)} – ${fmtTime(series.window_end)}`],
          ["Readings in window", `${q?.accepted ?? 0} accepted · ${q?.rejected ?? 0} rejected`],
          ["Rejected because", Object.entries(q?.rejected_by_reason ?? {}).map(([k, n]) => `${k.replace(/_/g, " ").toLowerCase()} ${n}`).join(", ") || "—"],
          ["Whole station", `${meta?.analysis?.accepted_readings ?? q?.station_accepted ?? "—"} of ${meta?.load?.counts?.usable_rows ?? q?.station_checked ?? "—"} readings accepted`],
          ["Station record", `${fmtTime(meta?.load?.first_observed_at)} – ${fmtTime(meta?.load?.last_observed_at)}`],
          ["Source file", meta?.load?.provenance?.raw_file ?? doc.analysis?.source?.raw_file ?? "—"],
          ["Timestamps", `UTC${meta?.load?.provenance?.assumed_utc_offset ?? ""} (${(meta?.load?.provenance?.timestamp_status ?? "").toLowerCase()})`],
          ["Datum", `${(meta?.load?.provenance?.datum ?? "—").replace(/_/g, " ")} (${(meta?.load?.provenance?.datum_status ?? "").toLowerCase()})`],
          ["Gauge zero", fmtNum(meta?.rl_zero_gauge_m, "m RL", 2)],
        ]} />
      </Disclosure>
    </>
  );
  return (
    <Card title="Historical river levels" icon="river" actions={<SourceBadge kind="historical" />}>
      <div className="fa-controls">
        <Segmented label="Station" value={station} onChange={onStation} options={stations.map((s) => ({ id: s, label: stationName(s) }))} />
        <Segmented label="Time range" value={range} onChange={onRange} options={RANGES} />
      </div>
      {body}
    </Card>
  );
}

/** The page body for an analysis document (pure; exported for tests). */
export function AnalyticsView(props: {
  doc: AnalysisDoc; series: SeriesDoc | null; seriesError: string | null; seriesLoading: boolean;
  station: string; range: SeriesRange; onStation: (s: string) => void; onRange: (r: SeriesRange) => void;
}) {
  const { doc } = props;
  return (
    <>
      <SummaryCards doc={doc} />
      {doc.forecast ? <ForecastSection f={doc.forecast} /> : <Empty>No forecast evaluation in this response.</Empty>}
      <HistoricalSection doc={doc} series={props.series} error={props.seriesError} loading={props.seriesLoading}
        station={props.station} range={props.range} onStation={props.onStation} onRange={props.onRange} />
    </>
  );
}

export function ForecastAnalyticsPage({ analysis, error }: { analysis: AnalysisDoc | null; error: string | null }) {
  const primary = analysis?.analysis?.primary_station ?? "UPPER_ANICUT";
  const [station, setStation] = useState<string | null>(null);
  const [range, setRange] = useState<SeriesRange>("7d");
  const [series, setSeries] = useState<{ doc: SeriesDoc | null; error: string | null; loading: boolean }>({ doc: null, error: null, loading: false });
  const current = station ?? primary;

  useEffect(() => {
    if (!analysis) return;
    const controller = new AbortController();
    setSeries((s) => ({ ...s, error: null, loading: true }));
    void fetchSeries(current, range, controller.signal)
      .then((r) => setSeries(r.ok ? { doc: r.value, error: null, loading: false } : { doc: null, error: r.error, loading: false }))
      .catch((e: Error) => { if (e.name !== "AbortError") setSeries({ doc: null, error: String(e), loading: false }); });
    return () => controller.abort();
  }, [analysis, current, range]);

  return (
    <div className="page analytics">
      <header className="page-head">
        <div className="title-row"><h2>Forecast &amp; Analytics</h2><SourceInfo /></div>
      </header>
      {analysis
        ? <AnalyticsView doc={analysis} series={series.doc} seriesError={series.error} seriesLoading={series.loading}
            station={current} range={range} onStation={setStation} onRange={setRange} />
        : <Empty>{error ? `Historical analysis unavailable: ${error}` : "Loading historical analysis…"}</Empty>}
    </div>
  );
}
