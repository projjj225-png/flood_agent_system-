// Forecast & Analytics: historical CWC river levels and the validated river-level models.
// Visual first; technical detail only inside collapsible sections. Every value comes from
// /dashboard/analysis and /dashboard/analysis/series; nothing is computed or filled in here,
// and a prediction is drawn only when the backend published it from fresh inputs.
import { useEffect, useState, type ReactNode } from "react";
import {
  Area, Bar, BarChart, CartesianGrid, Cell, ComposedChart, LabelList, Line, LineChart, ResponsiveContainer,
  Scatter, Tooltip, XAxis, YAxis,
} from "recharts";
import { fetchSeries } from "../api";
import type { AnalysisDoc, HorizonEvaluation, SeriesDoc, SeriesRange } from "../types";
import { epoch, fmtNum, fmtShort, fmtTime, isNum } from "../format";
import {
  forecastChartData, horizonCounts, horizonStatus, MODEL_NAMES, modelBars, modelName, validationChecks,
  type Forecast, type Metric,
} from "../forecastModel";
import { Card, Disclosure, Empty, Icon, KV, Pill, Stat } from "./ui";

export const SOURCE_LABELS = {
  historical: "HISTORICAL CWC",
  simulated: "SIMULATED LIVE",
  telemetry: "CWC TELEMETRY",
  model: "MODEL PREDICTION",
} as const;
export const RANGES: { id: SeriesRange; label: string }[] = [
  { id: "24h", label: "24 h" }, { id: "7d", label: "7 days" }, { id: "30d", label: "30 days" }, { id: "all", label: "All" },
];
const STATION_NAMES: Record<string, string> = { UPPER_ANICUT: "Upper Anicut", MUSIRI: "Musiri" };
const stationName = (id: string) => STATION_NAMES[id] ?? id;
const INK = "#1b3a63";
const GRID = "#e6ebf2";
const AXIS = { fontSize: 11, fill: "#5b6b80" };
const cm = (m?: number | null) => (isNum(m) ? `${(m * 100).toFixed(1)} cm` : "—");
const signedPct = (x?: number | null) => (isNum(x) ? `${x > 0 ? "+" : ""}${(x * 100).toFixed(1)}%` : "—");

function ageText(hours?: number | null) {
  if (!isNum(hours)) return "age unknown";
  if (hours < 48) return `${hours.toFixed(1)} h old`;
  return `${Math.round(hours / 24)} days old`;
}

export function SourceBadge({ kind }: { kind: keyof typeof SOURCE_LABELS }) {
  return <span className={`src-badge src-${kind}`}>{SOURCE_LABELS[kind]}</span>;
}

/** One concise explanation of the source labels, next to the page title. */
export function SourceInfo() {
  return (
    <span className="info-tip" tabIndex={0} aria-describedby="source-info">
      <Icon name="info" size={16} />
      <span role="tooltip" id="source-info" className="info-tip-body">
        <strong>Data sources</strong>
        <span><SourceBadge kind="historical" /> Measured readings from the CWC 2021–2025 export (past data).</span>
        <span><SourceBadge kind="telemetry" /> Current accepted CWC telemetry.</span>
        <span><SourceBadge kind="simulated" /> Generated by the demonstration engine.</span>
        <span><SourceBadge kind="model" /> Model output, shown only when validated and fed fresh data.</span>
        <span>None of these values change the risk, disaster state or permissions.</span>
      </span>
    </span>
  );
}

// ---- summary --------------------------------------------------------------------------

export function SummaryCards({ doc }: { doc: AnalysisDoc }) {
  const primary = doc.analysis?.primary_station ?? doc.forecast?.station_id ?? "";
  const st = doc.analysis?.stations?.[primary]?.analysis;
  const f = doc.forecast;
  const counts = horizonCounts(f);
  const fresh = f?.input?.status ?? st?.freshness?.status;
  return (
    <div className="fa-summary">
      <Stat label="Latest river level" value={fmtNum(st?.latest?.level_m, "m", 2)}
        note={<>{stationName(primary)} <SourceBadge kind="historical" /></>} />
      <Stat label="Latest observation" value={<span className="stat-time">{fmtTime(st?.latest?.observed_at)}</span>}
        note={ageText(st?.freshness?.age_hours ?? f?.input?.age_hours)} />
      <Stat label="Forecast availability" value={`${counts.published} / ${counts.total}`}
        note={<Pill tone={counts.published > 0 ? "ok" : "danger"}>{counts.published > 0 ? "AVAILABLE" : "NOT AVAILABLE"}</Pill>} />
      <Stat label="Data freshness" value={<Pill tone={fresh === "FRESH" ? "ok" : fresh === "STALE" ? "warn" : "unknown"}>{fresh ?? "UNKNOWN"}</Pill>}
        note={isNum(f?.input?.max_age_hours) ? `limit ${f?.input?.max_age_hours} h` : undefined} />
    </div>
  );
}

// ---- forecast --------------------------------------------------------------------------

export function HorizonCards({ f }: { f: Forecast }) {
  const horizons = f.evaluation?.horizons ?? [];
  if (!horizons.length) return <Empty>No forecast horizons were evaluated.</Empty>;
  return (
    <ul className="hz-row" aria-label="Forecast horizons">
      {horizons.map((h) => {
        const live = f.live?.find((x) => x.horizon_hours === h.horizon_hours);
        const s = horizonStatus(h, live, f);
        return (
          <li key={h.horizon_hours} className={`hz hz-${s.tone}`} title={s.details.join("\n") || undefined}>
            <span className="hz-h">+{h.horizon_hours} h</span>
            {s.published && live ? (
              <>
                <strong className="hz-level">{fmtNum(live.predicted_level_m, "m", 2)}</strong>
                <span className="hz-int">{live.interval_m?.length === 2 ? `${fmtNum(live.interval_m[0], "", 2)}–${fmtNum(live.interval_m[1], "m", 2)}` : "no interval"}</span>
              </>
            ) : <strong className="hz-level hz-none">—</strong>}
            <Pill tone={s.tone === "ok" ? "ok" : s.tone === "caution" ? "caution" : "danger"}>{s.published ? "PUBLISHED" : "NOT PUBLISHED"}</Pill>
            <span className="hz-reason">{s.published ? modelName(live?.model) : s.label}</span>
          </li>
        );
      })}
    </ul>
  );
}

export function ForecastChart({ f }: { f: Forecast }) {
  const { measured, predicted } = forecastChartData(f);
  if (!measured.length) return <Empty>No measured readings to plot.</Empty>;
  const rows = [
    ...measured.map((m) => ({ t: m.t, measured: m.measured })),
    ...predicted.map((p) => ({ t: p.t, predicted: p.predicted, band: p.range ?? undefined })),
  ].sort((a, b) => a.t - b.t);
  const values = [...measured.map((m) => m.measured), ...predicted.flatMap((p) => [p.predicted, ...(p.range ?? [])])];
  const pad = Math.max(0.05, (Math.max(...values) - Math.min(...values)) * 0.15);
  return (
    <figure className="chart" aria-label="Observed river level and published forecasts">
      <div className="chart-legend">
        <span><i className="sw sw-obs" /> Observed <SourceBadge kind="historical" /></span>
        <span><i className="sw sw-fc" /> Forecast (90% band)</span>
        {!predicted.length && <span className="muted">No published forecast to draw</span>}
      </div>
      <ResponsiveContainer width="100%" height={260}>
        <ComposedChart data={rows} margin={{ top: 8, right: 16, bottom: 0, left: 0 }}>
          <CartesianGrid stroke={GRID} vertical={false} />
          <XAxis dataKey="t" type="number" scale="time" domain={["dataMin", "dataMax"]} tick={AXIS} stroke={GRID}
            tickFormatter={(t: number) => fmtShort(new Date(t).toISOString())} minTickGap={48} />
          <YAxis domain={[Math.min(...values) - pad, Math.max(...values) + pad]} tick={AXIS} width={52} stroke={GRID}
            tickFormatter={(v: number) => v.toFixed(2)} />
          <Tooltip labelFormatter={(t) => (typeof t === "number" ? `${fmtShort(new Date(t).toISOString())} IST` : "")}
            formatter={(v: unknown, n: string) => [Array.isArray(v) ? `${fmtNum(v[0] as number, "", 2)}–${fmtNum(v[1] as number, "m", 2)}` : fmtNum(v as number, "m", 3),
              n === "measured" ? "Observed" : n === "predicted" ? "Forecast" : "90% band"]} />
          <Area dataKey="band" stroke="none" fill="#9cc0e4" fillOpacity={0.45} isAnimationActive={false} connectNulls={false} />
          <Line dataKey="measured" stroke={INK} strokeWidth={2} dot={false} isAnimationActive={false} connectNulls={false} />
          <Scatter dataKey="predicted" fill="#2d5f9a" isAnimationActive={false} />
        </ComposedChart>
      </ResponsiveContainer>
    </figure>
  );
}

export function ModelComparison({ h, metric }: { h: HorizonEvaluation | undefined; metric: Metric }) {
  const bars = modelBars(h, metric);
  if (!h || !bars.length) return <Empty>No validation results for this horizon.</Empty>;
  const selected = bars.find((b) => b.selected);
  return (
    <figure className="chart" aria-label={`Model comparison, validation ${metric === "mae_m" ? "MAE" : "RMSE"}`}>
      <ResponsiveContainer width="100%" height={44 * bars.length + 20}>
        <BarChart data={bars} layout="vertical" margin={{ top: 0, right: 56, bottom: 0, left: 0 }} barCategoryGap={8}>
          <XAxis type="number" hide domain={[0, "dataMax"]} />
          <YAxis type="category" dataKey="label" width={120} tick={AXIS} stroke={GRID} />
          <Tooltip formatter={(v: number) => [`${v.toFixed(1)} cm`, metric === "mae_m" ? "Validation MAE" : "Validation RMSE"]} />
          <Bar dataKey="cm" radius={[0, 4, 4, 0]} isAnimationActive={false}>
            {bars.map((b) => <Cell key={b.model} fill={b.published ? "#1f7a4a" : b.selected ? "#d4a514" : "#9fb0c4"} />)}
            <LabelList dataKey="cm" position="right" formatter={(v: number) => `${v.toFixed(1)} cm`} style={{ fontSize: 11, fill: "#33445c" }} />
          </Bar>
        </BarChart>
      </ResponsiveContainer>
      <figcaption className="small">
        {selected
          ? selected.published
            ? <><Pill tone="ok">PUBLISHED</Pill> {selected.fullName}: lowest validation error and passed every publishing check.</>
            : <><Pill tone="caution" >NOT PUBLISHED</Pill> {selected.fullName}: best on validation, but did not pass validation.</>
          : "No model was selected for this horizon."}
        {" "}Lower is better · Persistence is the no-change baseline.
      </figcaption>
    </figure>
  );
}

function PerformanceDetails({ f }: { f: Forecast }) {
  const horizons = f.evaluation?.horizons ?? [];
  return (
    <Disclosure summary="Model performance details">
      <p className="small muted">{f.evaluation?.publishing_rule}. Validation/test split is chronological.</p>
      {horizons.map((h) => (
        <div key={h.horizon_hours} className="perf">
          <h4>+{h.horizon_hours} h · {h.validation_status?.replace(/_/g, " ").toLowerCase()}
            {h.split?.samples && <span className="muted"> · {h.split.samples.validation} validation / {h.split.samples.test} test samples</span>}</h4>
          <div className="tbl-wrap">
            <table className="tbl">
              <thead><tr><th>Model</th><th>MAE</th><th>RMSE</th><th>Bias</th><th>R²</th><th>Skill vs persistence</th><th>Test MAE</th><th>Interval coverage</th></tr></thead>
              <tbody>{Object.keys(MODEL_NAMES).filter((m) => h.models?.[m]).map((m) => {
                const x = h.models![m];
                return (
                  <tr key={m} className={h.selected_model === m ? "is-selected" : ""}>
                    <td>{MODEL_NAMES[m]}{h.selected_model === m ? " (selected)" : ""}</td>
                    <td>{cm(x.validation?.mae_m)}</td><td>{cm(x.validation?.rmse_m)}</td><td>{cm(x.validation?.bias_m)}</td>
                    <td>{fmtNum(x.validation?.r2 ?? null, "", 3)}</td><td>{m === "persistence" ? "baseline" : signedPct(x.validation?.skill_vs_persistence)}</td>
                    <td>{cm(x.test?.mae_m)}</td><td>{isNum(x.interval?.test_coverage) ? `${Math.round(x.interval!.test_coverage! * 100)}%` : "—"}</td>
                  </tr>
                );
              })}</tbody>
            </table>
          </div>
          <ul className="checks">{validationChecks(h).map((c) => (
            <li key={c.label} className={c.pass ? "pass" : "fail"}><Icon name={c.pass ? "check" : "x"} size={12} /> {c.label} {c.value}</li>
          ))}</ul>
        </div>
      ))}
    </Disclosure>
  );
}

function Segmented<T extends string | number>({ label, value, options, onChange }: {
  label: string; value: T; options: { id: T; label: string }[]; onChange: (v: T) => void;
}) {
  return (
    <div className="segmented small-seg" role="radiogroup" aria-label={label}>
      {options.map((o) => (
        <button key={String(o.id)} role="radio" aria-checked={o.id === value} className={o.id === value ? "on" : ""}
          onClick={() => onChange(o.id)}>{o.label}</button>
      ))}
    </div>
  );
}

export function ForecastSection({ f }: { f: Forecast }) {
  const horizons = f.evaluation?.horizons ?? [];
  const [horizon, setHorizon] = useState(horizons[0]?.horizon_hours ?? 1);
  const [metric, setMetric] = useState<Metric>("mae_m");
  return (
    <Card title="River-level forecast" icon="analytics" actions={<SourceBadge kind="model" />}
      subtitle={`${stationName(f.station_id ?? "")} · published only when validated and fed fresh data`}>
      <HorizonCards f={f} />
      <div className="grid grid-fc">
        <div>
          <h4 className="sub-h">Observed vs forecast</h4>
          <ForecastChart f={f} />
        </div>
        <div>
          <div className="sub-head">
            <h4 className="sub-h">Model comparison</h4>
            <Segmented label="Error metric" value={metric} onChange={setMetric}
              options={[{ id: "mae_m" as Metric, label: "MAE" }, { id: "rmse_m" as Metric, label: "RMSE" }]} />
          </div>
          <Segmented label="Forecast horizon" value={horizon} onChange={setHorizon}
            options={horizons.map((h) => ({ id: h.horizon_hours, label: `+${h.horizon_hours} h` }))} />
          <ModelComparison h={horizons.find((h) => h.horizon_hours === horizon)} metric={metric} />
        </div>
      </div>
      <PerformanceDetails f={f} />
    </Card>
  );
}

